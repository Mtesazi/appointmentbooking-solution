CREATE TABLE email_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient VARCHAR(254) NOT NULL,
    subject VARCHAR(200) NOT NULL,
    body TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempt_count INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at TIMESTAMP WITH TIME ZONE,
    last_error VARCHAR(120),
    CONSTRAINT email_outbox_status_valid CHECK (status IN ('PENDING', 'FAILED', 'SENT', 'DEAD')),
    CONSTRAINT email_outbox_attempt_count_nonnegative CHECK (attempt_count >= 0)
);

CREATE INDEX idx_email_outbox_due ON email_outbox (next_attempt_at, created_at)
    WHERE status IN ('PENDING', 'FAILED');
